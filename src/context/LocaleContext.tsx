interface LocaleContextType {
  locale: Locale;
  setLocale: (loc: Locale) => void;
  toggleLocale: () => void;
  t: (
    key: string,
    paramsOrFallback?: Record<string, string | number> | string,
    fallback?: string
  ) => string;
}

const LocaleContext = createContext<LocaleContextType>({
  locale: 'id',
  setLocale: () => {},
  toggleLocale: () => {},
  t: (
    key: string,
    paramsOrFallback?: Record<string, string | number> | string,
    fallback?: string
  ) => (typeof paramsOrFallback === 'string' ? paramsOrFallback : fallback) || key,
});

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('id');

  useEffect(() => {
    const saved = localStorage.getItem('polylingua_locale') as Locale | null;
    if (saved === 'id' || saved === 'en') {
      queueMicrotask(() => {
        setLocaleState(saved);
      });
    }
  }, []);

  const setLocale = (newLocale: Locale) => {
    setLocaleState(newLocale);
    localStorage.setItem('polylingua_locale', newLocale);
  };

  const toggleLocale = () => {
    const next = locale === 'id' ? 'en' : 'id';
    setLocale(next);
  };

  const t = (
    key: string,
    paramsOrFallback?: Record<string, string | number> | string,
    fallback?: string
  ): string => {
    const dict = DICTIONARY[locale];
    const actualFallback = typeof paramsOrFallback === 'string' ? paramsOrFallback : fallback;
    const actualParams = typeof paramsOrFallback === 'object' ? paramsOrFallback : undefined;

    let text = dict && dict[key] ? dict[key] : (DICTIONARY.id[key] || actualFallback || key);

    if (actualParams) {
      Object.entries(actualParams).forEach(([paramKey, paramValue]) => {
        text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramValue));
      });
    }

    return text;
  };

  return (
    <LocaleContext.Provider value={{ locale, setLocale, toggleLocale, t }}>
      {children}
    </LocaleContext.Provider>
  );
}

export function useLocale() {
  return useContext(LocaleContext);
}
